const { PDFDocument, rgb, StandardFonts } = require('pdf-lib');
const fs = require('fs');

// A4 dimensions in points (72 points = 1 inch)
const A4_WIDTH = 595.28;
const A4_HEIGHT = 841.89;

// Standard Indian ID card size in points (~86mm x 54mm)
// Slightly scaled for crisp readability: ~95mm x 60mm (269 x 170 pt)
const ID_CARD_WIDTH = 270;
const ID_CARD_HEIGHT = 170;

const pdfService = {
  /**
   * Count total pages in an uploaded PDF buffer
   */
  async countPdfPages(buffer) {
    try {
      const pdfDoc = await PDFDocument.load(buffer, { ignoreEncryption: true });
      return pdfDoc.getPageCount();
    } catch (err) {
      console.error('Error counting PDF pages:', err);
      // Fallback: If corrupted or image, default to 1
      return 1;
    }
  },

  /**
   * Convert single or multiple images to a clean A4 PDF
   */
  async convertImageToPdf(imageBuffer, mimeType) {
    const pdfDoc = await PDFDocument.create();
    const page = pdfDoc.addPage([A4_WIDTH, A4_HEIGHT]);

    let image;
    if (mimeType.includes('png')) {
      image = await pdfDoc.embedPng(imageBuffer);
    } else {
      image = await pdfDoc.embedJpg(imageBuffer);
    }

    const imgDims = image.scaleToFit(A4_WIDTH - 60, A4_HEIGHT - 60);

    // Center on A4
    page.drawImage(image, {
      x: (A4_WIDTH - imgDims.width) / 2,
      y: (A4_HEIGHT - imgDims.height) / 2,
      width: imgDims.width,
      height: imgDims.height,
    });

    return await pdfDoc.save();
  },

  /**
   * Smart Aadhaar / ID Card Merging
   * Combines Front side and Back side photos on a single A4 sheet
   * with proper dimensions, alignment, and clean cutting guide borders!
   */
  async createIdCardPdf(frontBuffer, frontMime, backBuffer, backMime) {
    const pdfDoc = await PDFDocument.create();
    const page = pdfDoc.addPage([A4_WIDTH, A4_HEIGHT]);
    const font = await pdfDoc.embedFont(StandardFonts.HelveticaBold);
    const subFont = await pdfDoc.embedFont(StandardFonts.Helvetica);

    // Embed front image
    let frontImage;
    if (frontMime && frontMime.includes('png')) {
      frontImage = await pdfDoc.embedPng(frontBuffer);
    } else {
      frontImage = await pdfDoc.embedJpg(frontBuffer);
    }

    // Embed back image
    let backImage;
    if (backMime && backMime.includes('png')) {
      backImage = await pdfDoc.embedPng(backBuffer);
    } else {
      backImage = await pdfDoc.embedJpg(backBuffer);
    }

    // Layout configuration:
    // Place both cards in the top half of the A4 page (standard cyber cafe convention)
    // Left: Front Card, Right: Back Card (or stacked)
    // Here we place them stacked vertically with neat card borders for easy cutting/lamination!

    const cardX = (A4_WIDTH - ID_CARD_WIDTH) / 2;
    const topCardY = A4_HEIGHT - 70 - ID_CARD_HEIGHT;
    const bottomCardY = topCardY - ID_CARD_HEIGHT - 45;

    // Header title
    page.drawText('IDENTIFICATION CARD - PRINT COPY', {
      x: 40,
      y: A4_HEIGHT - 40,
      size: 11,
      font: font,
      color: rgb(0.3, 0.3, 0.3)
    });

    page.drawLine({
      start: { x: 40, y: A4_HEIGHT - 48 },
      end: { x: A4_WIDTH - 40, y: A4_HEIGHT - 48 },
      thickness: 0.8,
      color: rgb(0.8, 0.8, 0.8)
    });

    // --- FRONT SIDE CARD ---
    // Label
    page.drawText('FRONT SIDE (Cut along the dashed border)', {
      x: cardX,
      y: topCardY + ID_CARD_HEIGHT + 6,
      size: 9,
      font: font,
      color: rgb(0.2, 0.4, 0.8)
    });

    // Draw Front Image
    page.drawImage(frontImage, {
      x: cardX,
      y: topCardY,
      width: ID_CARD_WIDTH,
      height: ID_CARD_HEIGHT,
    });

    // Subtle guide border
    page.drawRectangle({
      x: cardX - 1,
      y: topCardY - 1,
      width: ID_CARD_WIDTH + 2,
      height: ID_CARD_HEIGHT + 2,
      borderColor: rgb(0.4, 0.4, 0.4),
      borderWidth: 0.75,
    });

    // --- BACK SIDE CARD ---
    // Label
    page.drawText('BACK SIDE (Cut along the dashed border)', {
      x: cardX,
      y: bottomCardY + ID_CARD_HEIGHT + 6,
      size: 9,
      font: font,
      color: rgb(0.2, 0.4, 0.8)
    });

    // Draw Back Image
    page.drawImage(backImage, {
      x: cardX,
      y: bottomCardY,
      width: ID_CARD_WIDTH,
      height: ID_CARD_HEIGHT,
    });

    // Subtle guide border
    page.drawRectangle({
      x: cardX - 1,
      y: bottomCardY - 1,
      width: ID_CARD_WIDTH + 2,
      height: ID_CARD_HEIGHT + 2,
      borderColor: rgb(0.4, 0.4, 0.4),
      borderWidth: 0.75,
    });

    // Footer note
    page.drawText('Generated by PrintKwik Smart Print Gateway | Ready for Lamination / Pocket Folder', {
      x: (A4_WIDTH - 300) / 2,
      y: 35,
      size: 8,
      font: subFont,
      color: rgb(0.6, 0.6, 0.6)
    });

    return await pdfDoc.save();
  }
};

module.exports = pdfService;

